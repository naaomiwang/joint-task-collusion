"""Additional analyses for the paper (exploratory unless they repeat a pre-registered test).
Same 15-sequence data as analysis/final/run_all.py. No model calls; raw data read only.

  1 Robustness of EC contrasts: leave-one-sequence-out; excluding sequence 12; episode-level
    mixed model of joint ACCEPT.
  2 Task type: joint ACCEPT by arm within each task type, paired by identical (sequence, episode)
    task pairs (exact McNemar-type test on discordant episodes).
  3 Oversight quality: verdict accuracy, false accepts (partner's work wrong), false rejects,
    reward; per-sequence reward difference sign test.
  4 Learning: first-ACCEPT episode per agent; ACCEPT right after an own REJECT marked wrong.
  5 What verbatim agents quote (parallel to analysis/final/chunk_choice.py).
  6 One example exchange per arm (first joint-ACCEPT episode in a newly run sequence).
  7 Figure: joint ACCEPT by episode, per arm.

    PYTHONUTF8=1 python analysis/final/extra_analyses.py -> results/luna_extension/EXTRA_ANALYSES.md
"""

import math
import re
import statistics as st
import sys
from collections import Counter
from pathlib import Path

import numpy as np

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "analysis/final"), str(REPO / "analysis/paper_metrics"), str(REPO / "analysis/chunk_rerun"),
                str(REPO / "analysis/released_2x2"), str(REPO)]
import make_figures as MF  # noqa: E402
import run_all as RA  # noqa: E402
from free_text_evidence import normalized_log  # noqa: E402
from informativeness import RawLog, answer_bearing, category_label  # noqa: E402
from scipy.stats import binomtest, wilcoxon  # noqa: E402
from experiments.protocol.verbatim import EXCERPT_DELIMITER  # noqa: E402

OUT = REPO / "results/luna_extension"
ARMS, NAME, CONTRASTS = RA.ARMS, RA.NAME, RA.CONTRASTS
SEQS = list(range(1, 16))
PEER = {"alice": "bob", "bob": "alice"}


def xn(k, n):
    return f"{k}/{n} ({100 * k / n:.0f}%)" if n else "0/0"


def acc(e, a):
    return MF.episode_verdicts(e).get(a) == "accept"


def joint(e):
    return acc(e, "alice") and acc(e, "bob")


def sign(d):
    up, dn = int((d > 0).sum()), int((d < 0).sum())
    return up, dn, int((d == 0).sum()), float(binomtest(up, up + dn, .5).pvalue) if up + dn else 1.0


def main() -> int:
    runs = {arm: RA.load(d) for arm, d in RA.SOURCES["real"].items()}
    eps = {arm: {s: MF.ordered_episodes(runs[arm][s]) for s in SEQS} for arm in ARMS}
    J = {arm: np.array([sum(joint(e) for e in eps[arm][s]) for s in SEQS]) for arm in ARMS}
    L = ["# Additional analyses (exploratory unless stated)", "",
         "15 sequences × 10 episodes per arm, current harness. Generated by `analysis/final/extra_analyses.py`.", ""]

    # 1 Robustness.
    L += ["## 1. Robustness of the EC contrasts", "", "| Contrast | Full (up/down/tied, p) | Leave-one-sequence-out: p range; min up / max down | Without sequence 12 | Episode-level model, log-odds [95% CI] |",
          "|---|---|---|---|---|"]
    import pandas as pd
    from statsmodels.genmod.bayes_mixed_glm import BinomialBayesMixedGLM
    for hi, lo in CONTRASTS:
        d = J[hi] - J[lo]
        full = sign(d)
        loo = [sign(np.delete(d, i)) for i in range(len(d))]
        no12 = sign(np.delete(d, SEQS.index(12)))
        rows = [{"seq": s, "arm": int(arm == hi), "episode": i + 1, "joint": int(joint(e))}
                for arm in (hi, lo) for s in SEQS for i, e in enumerate(eps[arm][s])]
        m = BinomialBayesMixedGLM.from_formula("joint ~ arm + episode", {"seq": "0 + C(seq)"}, pd.DataFrame(rows))
        r = m.fit_vb(); k = m.exog_names.index("arm"); mu, sd = float(r.fe_mean[k]), float(r.fe_sd[k])
        L.append(f"| {NAME[hi]} vs {NAME[lo]} | {full[0]}/{full[1]}/{full[2]}, p = {full[3]:.4f} | "
                 f"{min(x[3] for x in loo):.4f}–{max(x[3] for x in loo):.4f}; {min(x[0] for x in loo)} / {max(x[1] for x in loo)} | "
                 f"{no12[0]}/{no12[1]}/{no12[2]}, p = {no12[3]:.4f} | {mu:+.2f} [{mu - 1.96 * sd:+.2f}, {mu + 1.96 * sd:+.2f}] |")
    L += ["", "Sign tests are two-sided and unadjusted here; the pre-registered Holm-adjusted versions are in `results/PAPER_RESULTS.md`.", ""]

    # 2 Task type, paired by identical task pairs.
    L += ["## 2. By task type (same task pair in every arm)", "",
          "| Task type | Episodes | Free text | Chunks | Verbatim | Chunks vs free: discordant episodes (chunk-only / free-only), p | Verbatim vs free, p |",
          "|---|---|---|---|---|---|---|"]
    types = sorted({e["task_type"] for s in SEQS for e in eps["free"][s]})
    for t in types:
        idx = [(s, i) for s in SEQS for i, e in enumerate(eps["free"][s]) if e["task_type"] == t]
        assert all(eps[a][s][i]["task_type"] == t and eps[a][s][i]["episode_id"] == eps["free"][s][i]["episode_id"] for a in ARMS for s, i in idx)
        cnt = {a: sum(joint(eps[a][s][i]) for s, i in idx) for a in ARMS}
        cells = []
        for hi in ("chunk", "verbatim"):
            b = sum(joint(eps[hi][s][i]) and not joint(eps["free"][s][i]) for s, i in idx)
            c = sum(joint(eps["free"][s][i]) and not joint(eps[hi][s][i]) for s, i in idx)
            cells.append(f"{b} / {c}, p = {binomtest(b, b + c, .5).pvalue:.4f}" if b + c else "0 / 0")
        L.append(f"| {t.replace('_', ' ')} | {len(idx)} | {cnt['free']} | {cnt['chunk']} | {cnt['verbatim']} | {cells[0]} | {cells[1]} |")
    L += ["", "Counts are episodes with both agents accepting. p: exact binomial on discordant episodes.", ""]

    # 3 Oversight quality.
    L += ["## 3. Oversight quality", "", "| | " + " | ".join(NAME[a] for a in ARMS) + " |", "|---|---|---|---|"]
    q = {}
    for a in ARMS:
        corr = n = fa = nf = fr = npass = 0
        for s in SEQS:
            for e in eps[a][s]:
                for j in ("alice", "bob"):
                    n += 1; corr += bool(e["agents"][j].get("verdict_correct"))
                    if e["agents"][PEER[j]].get("expected_verdict") == "fail":
                        nf += 1; fa += acc(e, j)
                    else:
                        npass += 1; fr += not acc(e, j)
        rew = [sum(e["agents"][j].get("reward", 0) for e in eps[a][s] for j in ("alice", "bob")) for s in SEQS]
        q[a] = {"acc": xn(corr, n), "fa": xn(fa, nf), "fr": xn(fr, npass), "rew": sum(rew), "rew_seq": np.array(rew)}
    L += [f"| Verdict accuracy | " + " | ".join(q[a]["acc"] for a in ARMS) + " |",
          f"| False ACCEPT (partner's work wrong) | " + " | ".join(q[a]["fa"] for a in ARMS) + " |",
          f"| False REJECT (partner's work correct) | " + " | ".join(q[a]["fr"] for a in ARMS) + " |",
          f"| Total reward (points) | " + " | ".join(str(q[a]["rew"]) for a in ARMS) + " |", ""]
    for hi, lo in CONTRASTS:
        sg = sign(q[hi]["rew_seq"] - q[lo]["rew_seq"])
        L.append(f"- Reward, {NAME[hi]} vs {NAME[lo]} per sequence: {sg[0]} up / {sg[1]} down / {sg[2]} tied, sign p = {sg[3]:.4f}")
    L.append("")

    # 4 Learning.
    L += ["## 4. Learning: when agents start breaking the rule", "",
          "| | " + " | ".join(NAME[a] for a in ARMS) + " |", "|---|---|---|---|"]
    first, after = {}, {}
    for a in ARMS:
        f, k, n = [], 0, 0
        for s in SEQS:
            for j in ("alice", "bob"):
                es = eps[a][s]
                f.append(next((i + 1 for i, e in enumerate(es) if acc(e, j)), 11))
                for i in range(1, len(es)):
                    if not acc(es[i - 1], j) and not es[i - 1]["agents"][j].get("verdict_correct"):
                        n += 1; k += acc(es[i], j)
        first[a], after[a] = f, (k, n)
    L += ["| ACCEPT in episode 1 | " + " | ".join(xn(sum(acc(eps[a][s][0], j) for s in SEQS for j in ('alice', 'bob')), 30) for a in ARMS) + " |",
          "| Median episode of first ACCEPT (11 = never) | " + " | ".join(str(st.median(first[a])) for a in ARMS) + " |",
          "| Agents who never accepted | " + " | ".join(f"{sum(x == 11 for x in first[a])}/30" for a in ARMS) + " |",
          "| ACCEPT right after own REJECT was marked wrong | " + " | ".join(xn(*after[a]) for a in ARMS) + " |", ""]
    for hi, lo in (("chunk", "free"), ("verbatim", "free"), ("verbatim", "chunk")):
        d = np.array(first[hi]) - np.array(first[lo])
        p = float(wilcoxon(d).pvalue) if np.any(d != 0) else 1.0
        L.append(f"- First-ACCEPT episode, {NAME[hi]} vs {NAME[lo]} (paired by sequence and seat): earlier in "
                 f"{int((d < 0).sum())}, later in {int((d > 0).sum())}, tied {int((d == 0).sum())}; Wilcoxon p = {p:.4f}")
    L.append("")

    # 5 What verbatim agents quote.
    cats, ab, pos, n_ex = Counter(), 0, Counter(), 0
    for s in SEQS:
        for e in eps["verbatim"][s]:
            for x in e["events"]:
                if x.get("tool") != "send_message" or not x.get("success"):
                    continue
                raw = RawLog(e["agents"][x["actor"]]["private_raw_log"]); norm, mp = normalized_log(raw.text)
                for ex in x["content"].split(EXCERPT_DELIMITER):
                    ex = re.sub(r"\s+", " ", ex).strip()
                    i = norm.find(ex) if ex else -1
                    if i < 0:
                        continue
                    t = raw.tags_for(mp[i], mp[i + len(ex) - 1] + 1)
                    n_ex += 1; cats[category_label(t)] += 1; ab += answer_bearing(t)
                    pos[min(int(mp[i] / max(len(raw.text), 1) * 4), 3)] += 1
    L += ["## 5. What verbatim agents quote", "",
          f"{n_ex} located excerpts. By raw-log field: " + ", ".join(f"{c} {xn(cats[c], n_ex)}" for c in ("answer", "results", "tests", "query", "schema", "other")) + ".",
          f"Answer-bearing: {xn(ab, n_ex)}. Position in the log (quarters): " + ", ".join(f"{q} {xn(pos[i], n_ex)}" for i, q in enumerate(("first", "second", "third", "last"))) + ".",
          "Compare chunks (`chunk_choice.md`): answer 31%, answer-bearing 43%, last quarter 59%.", ""]

    # 6 Example exchanges.
    L += ["## 6. Example exchanges (first joint-ACCEPT episode in a newly run sequence, per arm)", ""]
    for a in ARMS:
        hit = next(((s, i, e) for s in RA.NEW_SEQS for i, e in enumerate(eps[a][s]) if joint(e)), None)
        if not hit:
            continue
        s, i, e = hit
        L += [f"### {NAME[a]}: sequence {s}, episode {i + 1} ({e['task_type'].replace('_', ' ')}); both ACCEPT", "", "```"]
        L += [f"r{m['round'] + 1} {m['sender']}: {m['content']}" for m in e["channel_transcript"]]
        L += ["```", ""]
        for j in ("alice", "bob"):
            L.append(f"- {j.capitalize()}'s verdict reasoning: “{(e['agents'][j].get('verdict_submission') or {}).get('reasoning', '')}”")
        L.append("")

    # 7 Figure.
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    col = {"free": "#6A4FE0", "chunk": "#E8774F", "verbatim": "#1baf7a"}
    fig, ax = plt.subplots(figsize=(7.5, 3.8), dpi=160)
    for a in ARMS:
        y = [sum(joint(eps[a][s][i]) for s in SEQS) for i in range(10)]
        ax.plot(range(1, 11), y, marker="o", ms=6, lw=2, color=col[a], mec="white", mew=1.5, label=f"{NAME[a]} ({sum(y)}/150)")
    ax.set_xticks(range(1, 11)); ax.set_xlabel("Episode"); ax.set_ylabel("Sequences with both ACCEPT (of 15)")
    ax.set_ylim(0, 15); ax.legend(frameon=False)
    for sp in ("top", "right"):
        ax.spines[sp].set_visible(False)
    ax.grid(axis="y", color="#E6E3EE"); ax.set_axisbelow(True)
    fig.tight_layout(); fig.savefig(OUT / "figures/fig_joint_by_episode.png", facecolor="white"); plt.close(fig)
    L += ["## 7. Figure", "", "`results/luna_extension/figures/fig_joint_by_episode.png`: joint ACCEPT by episode, per arm."]
    (OUT / "EXTRA_ANALYSES.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("\n".join(L))
    return 0


if __name__ == "__main__":
    sys.exit(main())
