"""Checks added after review. Same 15-sequence data as run_all.py; no model calls.

  1 Wilson intervals: TC, HC, ACCEPT of faulty work, and the always-accept baseline.
  2 First ACCEPT at the sequence level (mean of the two seats; never accepting coded as episode 11,
    which keeps the ordering exact for rank tests since a never-accepter is later than any accepter).
  3 Answer content per delivered message, chunks vs verbatim (same unit in both arms).
  4 Verbatim excerpts that could not be located in the sender's log: why.
  5 Reflections after a REJECT marked wrong that mention the raw-log rule, the missing log or incompleteness (keyword match).
  6 Persistence: an agent's ACCEPT rate in the episodes after its first ACCEPT, compared per sequence
    (mean over the sequence's agents that have at least one later episode).

    PYTHONUTF8=1 python analysis/final/review_checks.py   -> results/luna_extension/review_checks.md
"""

import json
import re
import sys
from pathlib import Path

import numpy as np
from scipy.stats import binomtest, wilcoxon
from statsmodels.stats.proportion import proportion_confint

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "analysis/final"), str(REPO / "analysis/paper_metrics"), str(REPO / "analysis/chunk_rerun"),
                str(REPO / "analysis/released_2x2"), str(REPO)]
import make_figures as MF  # noqa: E402
import run_all as RA  # noqa: E402
from free_text_evidence import normalized_log  # noqa: E402
from informativeness import RawLog, answer_bearing  # noqa: E402
from experiments.protocol.verbatim import EXCERPT_DELIMITER  # noqa: E402

ARMS, NAME = RA.ARMS, RA.NAME
SEQS = list(range(1, 16))
RULE = re.compile(r"raw.log|polic|incomplet|full log|complete log|partial|missing|untransmittable|channel limit"
                  r"|could not (be )?(transmit|sen)", re.I)


def wil(k, n):
    lo, hi = proportion_confint(k, n, method="wilson")
    return f"{k}/{n} ({100 * k / n:.0f}% [{100 * lo:.0f}, {100 * hi:.0f}])"


def accepts(e, a):
    return MF.episode_verdicts(e).get(a) == "accept"


def main() -> int:
    runs = {arm: RA.load(d) for arm, d in RA.SOURCES["real"].items()}
    eps = {a: {s: MF.ordered_episodes(runs[a][s]) for s in SEQS} for a in ARMS}
    L = ["# Checks added after review", "", "Generated by `analysis/final/review_checks.py`.", "", "## 1. Wilson intervals", ""]

    for a in ARMS:
        joint = [[accepts(e, "alice") and accepts(e, "bob") for e in eps[a][s]] for s in SEQS]
        tc = sum(any(j) for j in joint)
        hc = 0
        for j in joint:
            c = [int(x) for x in j]
            hc += any(c[t] and sum(1 - x for x in c[t:]) <= 1 for t in range(0, 6))  # onset tau <= T - 4 = 6 (1-based)
        bad = acc_bad = good = 0
        for s in SEQS:
            for e in eps[a][s]:
                for w in ("alice", "bob"):
                    correct_work = e["agents"][w]["verdict_correct"] == (e["agents"][w]["verdict"] == "accept")
                    good += correct_work; bad += not correct_work
                    acc_bad += (not correct_work) and e["agents"][w]["verdict"] == "accept"
        L.append(f"- {NAME[a]}: TC {wil(tc, 15)}; HC {wil(hc, 15)}; partner's work correct {good}/300 "
                 f"(= always-accept accuracy); ACCEPT of faulty work {wil(acc_bad, bad)}")

    # 2 First ACCEPT per sequence.
    L += ["", "## 2. First ACCEPT at the sequence level", ""]
    first = {a: np.array([[next((i + 1 for i, e in enumerate(eps[a][s]) if accepts(e, w)), 11) for w in ("alice", "bob")]
                          for s in SEQS], float) for a in ARMS}
    for a in ARMS:
        m = first[a].mean(axis=1)
        L.append(f"- {NAME[a]}: median of sequence means {np.median(m):.1f}; never-accepters {int((first[a] == 11).sum())}/30")
    for hi, lo in (("chunk", "free"), ("verbatim", "free"), ("verbatim", "chunk")):
        d = first[hi].mean(axis=1) - first[lo].mean(axis=1)
        up, dn = int((d < 0).sum()), int((d > 0).sum())
        p = binomtest(up, up + dn, .5).pvalue if up + dn else 1.0
        nz = d[d != 0]
        w = wilcoxon(nz).pvalue if len(nz) else float("nan")
        L.append(f"- {NAME[hi]} vs {NAME[lo]}: earlier in {up} sequences, later in {dn}, tied {15 - up - dn}; "
                 f"sign p = {p:.4f}; Wilcoxon p = {w:.4f}")

    # 3 Answer content per delivered message.
    L += ["", "## 3. Answer content per delivered message", ""]
    for a in ("chunk", "verbatim"):
        n = ab = 0
        for s in SEQS:
            for e in eps[a][s]:
                for m in e["events"]:
                    if m.get("tool") != "send_message" or not m.get("success"):
                        continue
                    raw = RawLog(e["agents"][m["actor"]]["private_raw_log"])
                    hit = False
                    if a == "chunk":
                        cid = int(m["chunk_id"]); st = raw.locate(m["content"], (cid - 1) * 200)
                        hit = st is not None and answer_bearing(raw.tags_for(st, st + len(m["content"])))
                    else:
                        norm, mp = normalized_log(raw.text)
                        for ex in m["content"].split(EXCERPT_DELIMITER):
                            ex = re.sub(r"\s+", " ", ex).strip(); i = norm.find(ex) if ex else -1
                            if i >= 0 and answer_bearing(raw.tags_for(mp[i], mp[i + len(ex) - 1] + 1)):
                                hit = True
                    n += 1; ab += hit
        L.append(f"- {NAME[a]}: messages with answer content {ab}/{n} ({100 * ab / n:.0f}%)")

    # 4 Unlocated verbatim excerpts.
    L += ["", "## 4. Unlocated verbatim excerpts", ""]
    miss = []
    for s in SEQS:
        for e in eps["verbatim"][s]:
            for m in e["events"]:
                if m.get("tool") != "send_message" or not m.get("success"):
                    continue
                raw = RawLog(e["agents"][m["actor"]]["private_raw_log"]); norm, _ = normalized_log(raw.text)
                unesc = re.sub(r"\s+", " ", json.loads(json.dumps(raw.text)).replace("\\n", "\n").replace('\\"', '"'))
                for ex in m["content"].split(EXCERPT_DELIMITER):
                    exn = re.sub(r"\s+", " ", ex).strip()
                    if exn and norm.find(exn) < 0:
                        miss.append((exn in unesc, exn[:90]))
    L.append(f"{len(miss)} unlocated; found in the JSON-unescaped log: {sum(m[0] for m in miss)}.")
    L += [f"  - {'unescaped' if f else 'NOT FOUND'}: {t!r}" for f, t in miss[:30]]

    # 5 Reflections after a wrong REJECT.
    L += ["", "## 5. Reflections after a REJECT marked wrong", "", f"Pattern: `{RULE.pattern}`", ""]
    for a in ARMS:
        n = k = 0
        for s in SEQS:
            for e in eps[a][s]:
                for w in ("alice", "bob"):
                    ag = e["agents"][w]
                    if ag["verdict"] == "reject" and not ag["verdict_correct"]:
                        n += 1; k += bool(RULE.search(ag.get("reflection") or ""))
        L.append(f"- {NAME[a]}: {k}/{n}")

    # 6 Persistence after the first ACCEPT.
    L += ["", "## 6. ACCEPT rate after an agent's first ACCEPT", ""]
    pers = {}
    for a in ARMS:
        k = n = 0
        per_seq = []
        for s in SEQS:
            rates = []
            for w in ("alice", "bob"):
                v = [accepts(e, w) for e in eps[a][s]]
                f = next((i for i, x in enumerate(v) if x), None)
                if f is None or f == len(v) - 1:
                    continue
                later = v[f + 1:]
                k += sum(later); n += len(later); rates.append(sum(later) / len(later))
            per_seq.append(np.mean(rates) if rates else np.nan)
        pers[a] = np.array(per_seq)
        L.append(f"- {NAME[a]}: {k}/{n} later episodes ACCEPT ({100 * k / n:.0f}%); "
                 f"sequences with a rate: {int(np.isfinite(pers[a]).sum())}")
    for hi, lo in (("chunk", "free"), ("verbatim", "free"), ("chunk", "verbatim")):
        d = pers[hi] - pers[lo]
        d = d[np.isfinite(d)]
        up, dn = int((d > 0).sum()), int((d < 0).sum())
        p = binomtest(up, up + dn, .5).pvalue if up + dn else 1.0
        nz = d[d != 0]
        w = wilcoxon(nz).pvalue if len(nz) else float("nan")
        L.append(f"- {NAME[hi]} vs {NAME[lo]}: higher in {up} sequences, lower in {dn}, tied {len(d) - up - dn} "
                 f"(n = {len(d)}); sign p = {p:.4f}; Wilcoxon p = {w:.4f}; mean difference {100 * d.mean():+.1f} points")
    text = "\n".join(L)
    (REPO / "results/luna_extension/review_checks.md").write_text(text + "\n", encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
