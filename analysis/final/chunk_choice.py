"""Exploratory (not pre-registered): how chunk-arm agents choose chunks. 15 sequences, current harness.

Each delivered chunk is tagged by the raw-log field it covers with the existing tagger
(released_2x2/informativeness: RawLog.tags_for, category_label, answer_bearing), plus its position
in the log (chunk_id / number of chunks), whether it repeats a chunk the agent already sent that
episode, and the round. Broken down by episode half (1-5 vs 6-10) and by round. No model calls.

    PYTHONUTF8=1 python analysis/final/chunk_choice.py  -> results/luna_extension/chunk_choice.md
"""

import math
import sys
from collections import Counter, defaultdict
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "analysis/final"), str(REPO / "analysis/paper_metrics"), str(REPO / "analysis/chunk_rerun"),
                str(REPO / "analysis/released_2x2"), str(REPO)]
import make_figures as MF  # noqa: E402
import run_all as RA  # noqa: E402
from informativeness import RawLog, answer_bearing, category_label  # noqa: E402

CATS = ("answer", "results", "tests", "query", "schema", "other")


def xn(k, n):
    return f"{k}/{n} ({100 * k / n:.0f}%)" if n else "0/0"


def main() -> int:
    runs = RA.load(RA.SOURCES["real"]["chunk"])
    sends = []
    for s in range(1, 16):
        for e in MF.ordered_episodes(runs[s]):
            ep = e["episode_index"] + 1
            for sender in ("alice", "bob"):
                raw = RawLog(e["agents"][sender]["private_raw_log"])
                n_chunks = math.ceil(len(raw.text) / 200)
                prev = []
                for x in e["events"]:
                    if x.get("tool") != "send_message" or not x.get("success") or x.get("actor") != sender:
                        continue
                    cid = int(x["chunk_id"])
                    st = raw.locate(x["content"], (cid - 1) * 200)
                    tags = raw.tags_for(st, st + len(x["content"])) if st is not None else set()
                    sends.append({"seq": s, "ep": ep, "sender": sender, "round": x["round"] + 1, "cid": cid, "n": n_chunks,
                                  "cat": category_label(tags), "ab": answer_bearing(tags), "repeat": cid in prev,
                                  "pos": (cid - 1) / max(n_chunks - 1, 1)})
                    prev.append(cid)
    N = len(sends)
    L = ["# How chunks are chosen (exploratory, not pre-registered)", "",
         f"Chunk arm, 15 sequences, {N} delivered chunks. Generated by `analysis/final/chunk_choice.py`.", "",
         "## What is sent (raw-log field the chunk covers)", "", "| Category | All | Episodes 1–5 | Episodes 6–10 |", "|---|---|---|---|"]
    early = [x for x in sends if x["ep"] <= 5]; late = [x for x in sends if x["ep"] > 5]
    for c in CATS:
        L.append(f"| {c} | {xn(sum(x['cat'] == c for x in sends), N)} | {xn(sum(x['cat'] == c for x in early), len(early))} | "
                 f"{xn(sum(x['cat'] == c for x in late), len(late))} |")
    L += ["", f"Answer-bearing (final answer, result rows or resolved IDs): {xn(sum(x['ab'] for x in sends), N)}; "
          f"episodes 1–5 {xn(sum(x['ab'] for x in early), len(early))}, 6–10 {xn(sum(x['ab'] for x in late), len(late))}.", "",
          "## By round", "", "| Round | Answer-bearing | Repeats a chunk already sent this episode | Chunk 1 (log start) |", "|---|---|---|---|"]
    for r in range(1, 6):
        g = [x for x in sends if x["round"] == r]
        L.append(f"| {r} | {xn(sum(x['ab'] for x in g), len(g))} | {xn(sum(x['repeat'] for x in g), len(g))} | "
                 f"{xn(sum(x['cid'] == 1 for x in g), len(g))} |")
    L += ["", "## Where in the log", ""]
    bins = Counter(min(int(x["pos"] * 4), 3) for x in sends)
    L.append("Position of the chosen chunk in the sender's log (quarters): " +
             ", ".join(f"{q}: {xn(bins[i], N)}" for i, q in enumerate(("first", "second", "third", "last"))) +
             f". Logs have {min(x['n'] for x in sends)}–{max(x['n'] for x in sends)} chunks.")
    # Per agent-episode: did the sender send at least one answer-bearing chunk, by half.
    ae = defaultdict(bool)
    for x in sends:
        ae[(x["seq"], x["ep"], x["sender"])] |= x["ab"]
    for lo, hi in ((1, 5), (6, 10)):
        v = [k for k in ae if lo <= k[1] <= hi]
        L.append(f"\nAgent-episodes sending ≥ 1 answer-bearing chunk, episodes {lo}–{hi}: {xn(sum(ae[k] for k in v), len(v))}.")
    reps = defaultdict(list)
    for x in sends:
        reps[(x["seq"], x["ep"], x["sender"])].append(x["cid"])
    distinct = Counter(len(set(v)) for v in reps.values())
    L += ["", "Distinct chunks per agent-episode (of 5 sends): " + ", ".join(f"{k}: {distinct[k]}" for k in sorted(distinct)) + "."]
    text = "\n".join(L)
    (REPO / "results/luna_extension/chunk_choice.md").write_text(text + "\n", encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
