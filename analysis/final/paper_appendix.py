"""Appendix text taken verbatim from the run records (paper/appendix_prompts.tex, paper/appendix_transcript.tex).

Prompts: sequence 2, episode 1, Alice's context in each arm. Transcript: sequence 12, episode 2 in each arm.
No model calls.

    PYTHONUTF8=1 python analysis/final/paper_appendix.py
"""

import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "analysis/final"), str(REPO / "analysis/paper_metrics"), str(REPO / "analysis/chunk_rerun"),
                str(REPO / "analysis/released_2x2"), str(REPO)]
import make_figures as MF  # noqa: E402
import run_all as RA  # noqa: E402

PAPER = REPO / "paper"
OPTS = "[breaklines,breakanywhere,fontsize=\\scriptsize,frame=single,framesep=1.5mm]"


def verb(text):
    return f"\\begin{{Verbatim}}{OPTS}\n{text.rstrip()}\n\\end{{Verbatim}}\n"


def main() -> int:
    runs = {arm: RA.load(d) for arm, d in RA.SOURCES["real"].items()}
    msgs = {a: MF.ordered_episodes(runs[a][2])[0]["agents"]["alice"]["messages"] for a in RA.ARMS}
    system = {a: next(m["content"] for m in msgs[a] if m["role"] == "system") for a in RA.ARMS}
    assert system["free"] == system["chunk"] == system["verbatim"], "system prompts differ between arms"
    users = [m["content"] for m in msgs["free"] if m["role"] == "user"]
    out = ["% Generated by analysis/final/paper_appendix.py from the run records. Edit the generator, not this file.",
           "\\subsection{System prompt (identical under all interfaces)}", verb(system["free"]),
           "\\subsection{Runner messages in one episode (free text)}",
           "All messages Alice received in episode 1 of sequence 2, in order. Messages tagged \\texttt{[from=bob]} are Bob's.",
           verb("\n\n----\n\n".join(users))]
    for a, title in (("chunk", "Chunks"), ("verbatim", "Verbatim")):
        first = next(m["content"] for m in msgs[a] if m["role"] == "user" and "(round 1 of 5)" in m["content"])
        lines = first.split("\n")
        keep, n_chunks = [], 0
        for ln in lines:
            if ln.startswith("chunk "):
                n_chunks += 1
                if n_chunks > 2:
                    continue
            keep.append(ln)
        note = f" The list of chunks is cut after chunk 2 of {n_chunks}." if n_chunks > 2 else ""
        out += [f"\\subsection{{Round instruction, {title.lower()} interface}}",
                f"Round 1 instruction in the same episode.{note}", verb("\n".join(keep))]
    (PAPER / "appendix_prompts.tex").write_text("\n".join(out) + "\n", encoding="utf-8")

    out = ["% Generated by analysis/final/paper_appendix.py from the run records. Edit the generator, not this file."]
    for a in RA.ARMS:
        e = MF.ordered_episodes(runs[a][12])[1]
        v = MF.episode_verdicts(e)
        lines = [f"r{int(x['round']) + 1} {x['actor'].capitalize()}: {x['content']}" for x in e["events"]
                 if x.get("tool") == "send_message" and x.get("success") in (True, "True")]
        out += [f"\\subsection{{{RA.NAME[a]}: Alice {v['alice'].upper()}, Bob {v['bob'].upper()}}}", verb("\n".join(lines))]
        for w in ("alice", "bob"):
            r = (e["agents"][w].get("verdict_submission") or {}).get("reasoning", "")
            out.append(verb(f"{w.capitalize()}'s verdict ({v[w].upper()}): {r}"))
    (PAPER / "appendix_transcript.tex").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("wrote", PAPER / "appendix_prompts.tex", PAPER / "appendix_transcript.tex")
    return 0


if __name__ == "__main__":
    sys.exit(main())
