"""Exploratory (not pre-registered): reciprocity in the Luna extension, all three arms.

Does an agent ACCEPT more in episode t when its partner ACCEPTED its work in episode t-1?
Shared upward trends and an agent's own persistence would create that association without any
responsiveness, so the model controls for both:

  accept_t ~ partner_accepted_me_{t-1} + own_accept_{t-1} + episode + (1|sequence) + (1|sequence:agent)

Bayesian mixed logistic (statsmodels BinomialBayesMixedGLM, VB), episodes 2-10, per arm. Also a
sequence-level check: per sequence, ACCEPT rate after partner-ACCEPT minus after partner-REJECT
(sequences with both cases), exact sign test and Wilcoxon. Same 15-sequence data as run_all.py.

    PYTHONUTF8=1 python analysis/final/reciprocity.py   -> results/luna_extension/reciprocity.md
"""

import sys
from pathlib import Path

import numpy as np
import pandas as pd
from statsmodels.genmod.bayes_mixed_glm import BinomialBayesMixedGLM

REPO = Path(__file__).resolve().parents[2]
sys.path[:0] = [str(REPO / "analysis/final"), str(REPO / "analysis/paper_metrics"), str(REPO / "analysis/chunk_rerun"),
                str(REPO / "analysis/released_2x2"), str(REPO)]
import make_figures as MF  # noqa: E402
import run_all as RA  # noqa: E402

PEER = {"alice": "bob", "bob": "alice"}


def rows(runs):
    out = []
    for s, r in runs.items():
        eps = MF.ordered_episodes(r)
        v = [MF.episode_verdicts(e) for e in eps]
        for t in range(1, len(eps)):
            for a in ("alice", "bob"):
                out.append({"seq": s, "sa": f"{s}_{a}", "episode": t + 1,
                            "accept": int(v[t].get(a) == "accept"),
                            "partner_prev": int(v[t - 1].get(PEER[a]) == "accept"),
                            "own_prev": int(v[t - 1].get(a) == "accept")})
    return pd.DataFrame(out)


def main() -> int:
    runs = {arm: RA.load(d) for arm, d in RA.SOURCES["real"].items()}
    seqs = list(range(1, 16))
    L = ["# Reciprocity (exploratory, not pre-registered)", "",
         "Does an agent ACCEPT more after its partner ACCEPTED its work in the previous episode? "
         "15 sequences, episodes 2–10, both agents. Generated by `analysis/final/reciprocity.py`.", "",
         "| Arm | ACCEPT after partner ACCEPT | after partner REJECT | Partner-ACCEPT effect, adjusted (log-odds [95% CI]) | Own previous ACCEPT (log-odds) | Sequences up/down/tied, sign p | Wilcoxon p |",
         "|---|---|---|---|---|---|---|"]
    for arm in RA.ARMS:
        df = rows({s: runs[arm][s] for s in seqs})
        a, b = df[df.partner_prev == 1], df[df.partner_prev == 0]
        m = BinomialBayesMixedGLM.from_formula("accept ~ partner_prev + own_prev + episode",
                                               {"seq": "0 + C(seq)", "sa": "0 + C(sa)"}, df)
        r = m.fit_vb()
        est = {n: (float(r.fe_mean[i]), float(r.fe_sd[i])) for i, n in enumerate(m.exog_names)}
        pm, ps = est["partner_prev"]; om, _ = est["own_prev"]
        d = []
        for s, g in df.groupby("seq"):
            x, y = g[g.partner_prev == 1], g[g.partner_prev == 0]
            if len(x) and len(y):
                d.append(x.accept.mean() - y.accept.mean())
        d = np.array(d)
        st = MF.sign_test(d); w = MF.wilcox(d)
        L.append(f"| {RA.NAME[arm]} | {int(a.accept.sum())}/{len(a)} | {int(b.accept.sum())}/{len(b)} | "
                 f"{pm:+.2f} [{pm - 1.96 * ps:+.2f}, {pm + 1.96 * ps:+.2f}] | {om:+.2f} | "
                 f"{st['up']}/{st['down']}/{st['tied']} (n = {len(d)}), p = {st['p']:.3f} | "
                 f"{'n/a' if w is None else f'{w:.3f}'} |")
    L += ["", "The adjusted model controls for the agent's own previous verdict and episode number; variational-Bayes "
          "intervals tend to be narrow. The sequence-level tests use only sequences where both cases occur."]
    text = "\n".join(L)
    (REPO / "results/luna_extension/reciprocity.md").write_text(text + "\n", encoding="utf-8")
    print(text)
    return 0


if __name__ == "__main__":
    sys.exit(main())
